# ── verbatim shared blocks (extracted from the reference prompt) ────────────

def section(text: str, start: str, end: str | None = None) -> str:
    lines = text.split("\n")
    si = next(i for i, l in enumerate(lines) if l.startswith(start))
    if end is None:
        return "\n".join(lines[si:]).rstrip() + "\n"
    ei = next(i for i, l in enumerate(lines) if l.startswith(end))
    return "\n".join(lines[si:ei]).rstrip() + "\n"


